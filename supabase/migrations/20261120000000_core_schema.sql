create table kc_contact_requests (
    id uuid primary key default gen_random_uuid(),
    client_id uuid not null references kc_clients(id) on delete cascade,
    message text not null,
    source text not null default 'landing',
    status text not null default 'new' check (status in ('new','contacted','qualified','won','lost','spam')),
    ip_hash text,
    user_agent text,
    email_sent_at timestamptz,
    email_error text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index kc_contact_requests_status_idx on kc_contact_requests(status);
create index kc_contact_requests_created_at_idx on kc_contact_requests(created_at desc);
create index kc_contact_requests_ip_created_idx on kc_contact_requests(ip_hash, created_at);

create table kc_contact_request_services (
    request_id uuid not null references kc_contact_requests(id) on delete cascade,
    service_id smallint not null references kc_services(id),
    primary key (request_id, service_id)
);

create table kc_projects (
    id uuid primary key default gen_random_uuid(),
    client_id uuid not null references kc_clients(id) on delete cascade,
    request_id uuid references kc_contact_requests(id) on delete set null,
    name text not null,
    description text,
    status text not null default 'proposal' check (status in ('proposal','active','paused','done','cancelled')),
    starts_on date,
    ends_on date,
    budget numeric(12,2),
    currency char(3) not null default 'MXN',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create table kc_project_services (
    project_id uuid not null references kc_projects(id) on delete cascade,
    service_id smallint not null references kc_services(id),
    primary key (project_id, service_id)
);

create function kc_set_updated_at() returns trigger language plpgsql set search_path = public as $$
begin new.updated_at = now(); return new; end;
$$;
create trigger kc_clients_updated_at before update on kc_clients for each row execute function kc_set_updated_at();
create trigger kc_contact_requests_updated_at before update on kc_contact_requests for each row execute function kc_set_updated_at();
create trigger kc_projects_updated_at before update on kc_projects for each row execute function kc_set_updated_at();

create function kc_submit_contact_request(
    p_full_name text, p_email text, p_message text, p_service_names text[], p_ip_hash text, p_user_agent text
) returns uuid language plpgsql security definer set search_path = public as $$
declare kc_client_id uuid; kc_request_id uuid;
begin
    insert into kc_clients(full_name, email) values (p_full_name, p_email)
    on conflict ((lower(email))) do update set full_name = excluded.full_name
    returning id into kc_client_id;
    insert into kc_contact_requests(client_id, message, ip_hash, user_agent)
    values (kc_client_id, p_message, p_ip_hash, p_user_agent) returning id into kc_request_id;
    insert into kc_contact_request_services(request_id, service_id)
    select kc_request_id, s.id from kc_services s
    where s.is_active and s.name = any(coalesce(p_service_names, array[]::text[]));
    return kc_request_id;
end;
$$;

create function kc_count_recent_requests(p_ip_hash text, p_window interval) returns integer
language sql stable set search_path = public as $$
    select count(*)::integer from kc_contact_requests
    where ip_hash = p_ip_hash and created_at >= now() - p_window;
$$;
